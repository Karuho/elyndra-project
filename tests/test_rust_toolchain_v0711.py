def test_rustfmt_uses_check_mode_without_writing_files(
    isolated_home: ElyndraPaths,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    project = _rust_project(Path.home() / "Proyectos" / "rust-fmt")
    source = project / "src" / "lib.rs"
    before = source.read_text(encoding="utf-8")
    log = Path.home() / "cargo-fmt.log"
    _executable(
        project / ".venv" / "bin" / "cargo",
        f"#!/bin/sh\nprintf '%s\\n' \"$*\" > '{log}'\nexit 0\n",
    )
    monkeypatch.setenv("PATH", "")
    app = ElyndraApplication.load(isolated_home)

