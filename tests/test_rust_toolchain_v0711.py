def _executable(path: Path, content: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    path.chmod(0o755)
    return path


def _rust_project(root: Path, *, lock: bool = True, tests: bool = True) -> Path:
    root.mkdir(parents=True)
    (root / "Cargo.toml").write_text(
        "[package]\n"
        'name = "demo"\n'
        'version = "0.1.0"\n'
        'edition = "2021"\n\n'
        "[dependencies]\n"
        'serde = "1"\n',
        encoding="utf-8",
    )
    if lock:
        (root / "Cargo.lock").write_text(
            "# This file is automatically @generated by Cargo.\nversion = 3\n",
            encoding="utf-8",
        )
    (root / "src").mkdir()
    (root / "src" / "lib.rs").write_text(
        "pub fn add(a: i32, b: i32) -> i32 { a + b }\n",
        encoding="utf-8",
    )
    if tests:
        (root / "tests").mkdir()
        (root / "tests" / "add.rs").write_text(
            "#[test]\nfn adds() { assert_eq!(demo::add(1, 2), 3); }\n",
            encoding="utf-8",
        )
    return root


