def test_rust_profile_and_control_center(isolated_home: ElyndraPaths) -> None:
    project = _rust_project(Path.home() / "Proyectos" / "rust-profile")
    app = ElyndraApplication.load(isolated_home)
    service = ElyndraWebService(app)

    profile = service.save_rust_profile(
        {
            "project_root": str(project),
            "clippy_enabled": False,
            "feature_mode": "all",
            "max_rust_files": 222,
        }
    )
    overview = service.control_overview()
    projects = service.control_projects()

    assert profile["clippy_enabled"] is False
    assert profile["feature_mode"] == "all"
    assert profile["max_rust_files"] == 222
    assert "target" in profile["exclude_paths"]
    assert overview["rust_profiles"] == 1
    assert "rust_verifications" in overview
    assert projects["rust_profiles"][0]["project_root"] == str(project)
    assert len(app.skills.list_all()) == 102
    with app.database.connect() as connection:
        version = connection.execute(
            "SELECT value FROM schema_meta WHERE key = 'schema_version'"
        ).fetchone()[0]
    assert version == "51"


